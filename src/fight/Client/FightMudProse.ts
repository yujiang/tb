/** 未配置技能action及角色出手文本时，按效果函数与魔法/物理选择通用出招。 */
export function mudActionTexts(skill: SkillData | undefined): readonly string[] {
	if (Object.prototype.hasOwnProperty.call(functions, skill?.func)) return functions[skill.func];

	if (skill?.magic) return magic;

	return physical;
}

